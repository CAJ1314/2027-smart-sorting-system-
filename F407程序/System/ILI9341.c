/* ================================================================
   SPI 底层
   ================================================================ */
/* Software SPI mode 0: SDI=PE9, CLK=PE8, CS=PG1, DC=PF15.
 * SDO is disconnected; no display readback is required. */
static void SPI_WriteByte(uint8_t data)
{
    uint8_t bit;
    for (bit = 0; bit < 8; bit++) {
        GPIO_ResetBits(ILI9341_CLK_PORT, ILI9341_CLK_PIN);
        if (data & 0x80) GPIO_SetBits(ILI9341_SDI_PORT, ILI9341_SDI_PIN);
        else GPIO_ResetBits(ILI9341_SDI_PORT, ILI9341_SDI_PIN);
        Delay_us(1);
        GPIO_SetBits(ILI9341_CLK_PORT, ILI9341_CLK_PIN);
        Delay_us(1);
        data <<= 1;
    }
    GPIO_ResetBits(ILI9341_CLK_PORT, ILI9341_CLK_PIN);
}

static void ILI9341_SPI_Init(void)
{
    GPIO_InitTypeDef g;
    RCC_AHB1PeriphClockCmd(RCC_AHB1Periph_GPIOE | RCC_AHB1Periph_GPIOG |
                           RCC_AHB1Periph_GPIOF, ENABLE);
    GPIO_StructInit(&g);
    g.GPIO_Mode = GPIO_Mode_OUT;
    g.GPIO_Speed = GPIO_Speed_50MHz;
    g.GPIO_OType = GPIO_OType_PP;
    g.GPIO_PuPd = GPIO_PuPd_NOPULL;
    GPIO_SetBits(ILI9341_CS_PORT, ILI9341_CS_PIN);
    GPIO_ResetBits(ILI9341_CLK_PORT, ILI9341_CLK_PIN);
    g.GPIO_Pin = ILI9341_CLK_PIN | ILI9341_SDI_PIN;
    GPIO_Init(ILI9341_CLK_PORT, &g);
    g.GPIO_Pin = ILI9341_CS_PIN;
    GPIO_Init(ILI9341_CS_PORT, &g);
    g.GPIO_Pin = ILI9341_DC_PIN;
    GPIO_Init(ILI9341_DC_PORT, &g);
    ILI9341_CS_HIGH();
    ILI9341_DC_HIGH();
}

/* ================================================================
   ILI9341 底层写操作
   ================================================================ */
void ILI9341_WriteCmd(uint8_t cmd)
{
    ILI9341_DC_LOW();
    ILI9341_CS_LOW();
    SPI_WriteByte(cmd);
    ILI9341_CS_HIGH();
}

void ILI9341_WriteData(uint8_t data)
{
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    SPI_WriteByte(data);
    ILI9341_CS_HIGH();
}

void ILI9341_WriteData16(uint16_t data)
{
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    SPI_WriteByte((uint8_t)(data >> 8));
    SPI_WriteByte((uint8_t)(data & 0xFF));
    ILI9341_CS_HIGH();
}

