void ILI9341_SetWindow(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2)
{
    ILI9341_WriteCmd(0x2A);
    ILI9341_WriteData16(x1);
    ILI9341_WriteData16(x2);

    ILI9341_WriteCmd(0x2B);
    ILI9341_WriteData16(y1);
    ILI9341_WriteData16(y2);

    ILI9341_WriteCmd(0x2C);
}

void ILI9341_FillScreen(uint16_t color)
{
    ILI9341_FillRect(0, 0, ILI9341_WIDTH, ILI9341_HEIGHT, color);
}

void ILI9341_FillRect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    uint32_t n = (uint32_t)w * h;

    if (x + w > ILI9341_WIDTH)  return;
    if (y + h > ILI9341_HEIGHT) return;

    ILI9341_SetWindow(x, y, x + w - 1, y + h - 1);

    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    while (n--)
    {
        SPI_WriteByte((uint8_t)(color >> 8));
        SPI_WriteByte((uint8_t)(color & 0xFF));
    }
    ILI9341_CS_HIGH();
}

/* ================================================================
   文字绘制 (8x16 ASCII, 支持 1x/2x 缩放)
   ================================================================ */

static void ILI9341_DrawChar(uint16_t x, uint16_t y, char ch,
                             uint16_t color, uint16_t bg, uint8_t scale)
{
    uint8_t col, row, sy, sx;

    if (ch < 0x20 || ch > 0x7E) return;

    const uint8_t *p = FONT_8x16[ch - 0x20];

    ILI9341_FillRect(x, y, 8 * scale, 16 * scale, bg);

    ILI9341_SetWindow(x, y, x + 8 * scale - 1, y + 16 * scale - 1);
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();

    /* This FONT_8x16 table is column-major: p[(row/8)*8 + col] is one column
       of an 8-row band and bit0 is that band's top pixel. Reading p[row]
       with bit7 would render garbage. */
    for (row = 0; row < 16; row++)
    {
        for (sy = 0; sy < scale; sy++)
        {
            for (col = 0; col < 8; col++)
            {
                uint16_t c = (p[(row / 8) * 8 + col] >> (row % 8)) & 0x01 ? color : bg;
                for (sx = 0; sx < scale; sx++)
                {
                    SPI_WriteByte((uint8_t)(c >> 8));
                    SPI_WriteByte((uint8_t)(c & 0xFF));
                }
            }
        }
    }

    ILI9341_CS_HIGH();
}

void ILI9341_DrawString(uint16_t x, uint16_t y, const char *str,
                        uint16_t color, uint16_t bg, uint8_t scale)
{
    while (*str)
    {
        ILI9341_DrawChar(x, y, *str, color, bg, scale);
        x += 8 * scale;
        if (x + 8 * scale > ILI9341_WIDTH) { x = 0; y += 16 * scale; }
        str++;
    }
}

/* Image2LCD: RGB565, horizontal scan, no header, high byte first.
 * Reject invalid length and bounds before writing to the display. */
void ILI9341_DrawImageRGB565(uint16_t x, uint16_t y,
    uint16_t w, uint16_t h, const uint8_t *pixels, uint32_t length)
{
    uint32_t i, needed;
    if (!pixels || !w || !h || x >= ILI9341_WIDTH || y >= ILI9341_HEIGHT) return;
    if (w > ILI9341_WIDTH - x || h > ILI9341_HEIGHT - y) return;
    needed = (uint32_t)w * h * 2u;
    if (length != needed) return;
    ILI9341_SetWindow(x, y, x + w - 1, y + h - 1);
    ILI9341_DC_HIGH();
    ILI9341_CS_LOW();
    for (i = 0; i < needed; i++) SPI_WriteByte(pixels[i]);
    ILI9341_CS_HIGH();
}
