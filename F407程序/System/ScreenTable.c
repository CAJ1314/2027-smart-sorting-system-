/* 8x16 digit, row first, bit7 leftmost. Returns 0 when the digit has no glyph. */
static uint8_t DrawDigit(uint16_t x, uint16_t y, uint8_t d)
{
    const uint8_t *g;
    uint8_t pixels[8 * 16 * 2];
    uint16_t row, col, color, index;

    switch (d)
    {
        case 1U: g = FONT_D1; break;
        case 2U: g = FONT_D2; break;
        case 3U: g = FONT_D3; break;
        case 4U: g = FONT_D4; break;
        case 5U: g = FONT_D5; break;
        case 6U: g = FONT_D6; break;
        default: return 0U;
    }

    for (row = 0U; row < 16U; row++)
    {
        for (col = 0U; col < 8U; col++)
        {
            color = (g[row] & (0x80u >> col)) ? ILI9341_BLACK : ILI9341_WHITE;
            index = (uint16_t)((row * 8U + col) * 2U);
            pixels[index] = (uint8_t)(color >> 8);
            pixels[index + 1] = (uint8_t)color;
        }
    }
    ILI9341_DrawImageRGB565(x, y, 8U, 16U, pixels, sizeof(pixels));
    return 1U;
}
/* Keyed by the full (color, shape) category, but only the shape is drawn. */
static uint8_t ScreenCategory[6] = {0U, 0U, 0U, 0U, 0U, 0U};
static uint8_t ScreenCount[6] = {0U, 0U, 0U, 0U, 0U, 0U};

/* category = color * 8 + shape. Unknown color (0) falls back to color 1. */
static const uint8_t *CategoryPicture(uint8_t category)
{
    uint8_t color = (uint8_t)(category / 8U);
    uint8_t shape = (uint8_t)(category % 8U);

    if (shape < 1U || shape > 7U) return 0;
    if (color < 1U || color > 7U) color = 1U;
    if (shape == 4U) return g_sphere_picture[color - 1U];
    return g_block_picture[(uint8_t)((color - 1U) * 7U + (shape - 1U))];
}

static void ClearDataRow(uint8_t slot)
{
    uint16_t y = (uint16_t)(54U + slot * 44U);

    /* Clear cell interiors only; keep the black grid lines intact. */
    ILI9341_FillRect(2U, y, 26U, 42U, ILI9341_WHITE);   /* 序号 */
    ILI9341_FillRect(30U, y, 68U, 42U, ILI9341_WHITE);  /* 名称 */
    ILI9341_FillRect(100U, y, 100U, 42U, ILI9341_WHITE);/* 图片 */
    ILI9341_FillRect(202U, y, 35U, 42U, ILI9341_WHITE); /* 次数 */
}

void ScreenTable_ResetData(void)
{
    uint8_t i;
    for (i = 0U; i < 6U; ++i)
    {
        ScreenCategory[i] = 0U;
        ScreenCount[i] = 0U;
        ClearDataRow(i);
    }
}

void ScreenTable_UpdateItem(uint8_t shape, uint8_t category)
{
    uint8_t i;
    uint8_t slot = 6U;
    uint16_t y;
    char text[4];

    if (shape < 1U || shape > 7U || category == 0U) return;

    for (i = 0U; i < 6U; ++i)
    {
        if (ScreenCategory[i] == category)
        {
            slot = i;
            break;
        }
    }

    if (slot == 6U)
    {
        for (i = 0U; i < 6U; ++i)
        {
            if (ScreenCategory[i] == 0U)
            {
                slot = i;
                ScreenCategory[i] = category;
                break;
            }
        }
    }

    if (slot == 6U) return;

    ScreenCount[slot]++;
    y = (uint16_t)(54U + slot * 44U);

    ClearDataRow(slot);

    if (DrawDigit(7U, (uint16_t)(y + 13U), (uint8_t)(slot + 1U)) == 0U)
    {
        text[0] = (char)('1' + slot);
        text[1] = '\0';
        ILI9341_DrawString(7U, (uint16_t)(y + 13U), text, ILI9341_BLACK, ILI9341_WHITE, 1U);
    }

    DrawShapeName(shape, 40U, (uint16_t)(y + 13U));

    {
        const uint8_t *picture = CategoryPicture(category);
        if (picture != 0)
        {
            ILI9341_DrawImageRGB565(114U, (uint16_t)(y + 1U),
                BLOCK_PICTURE_W, BLOCK_PICTURE_HEIGHT, picture, BLOCK_PICTURE_BYTES);
        }
    }

    if (DrawDigit(211U, (uint16_t)(y + 13U), ScreenCount[slot]) == 0U)
    {
        if (ScreenCount[slot] < 10U)
        {
            text[0] = (char)('0' + ScreenCount[slot]);
            text[1] = '\0';
        }
        else
        {
            text[0] = (char)('0' + (ScreenCount[slot] / 10U));
            text[1] = (char)('0' + (ScreenCount[slot] % 10U));
            text[2] = '\0';
        }
        ILI9341_DrawString(211U, (uint16_t)(y + 13U), text, ILI9341_BLACK, ILI9341_WHITE, 1U);
    }
}
