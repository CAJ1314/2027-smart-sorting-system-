/* A small RGB565 buffer sends a glyph as one rectangle. */
static void DrawGlyph(uint16_t x, uint16_t y, const uint8_t *glyph)
{
    uint8_t pixels[16 * 16 * 2];
    uint16_t row, col, color, index;
    for (row = 0; row < 16; row++) {
        for (col = 0; col < 16; col++) {
            color = (glyph[row * 2 + col / 8] & (0x80u >> (col % 8)))
                    ? ILI9341_BLACK : ILI9341_WHITE;
            index = (row * 16 + col) * 2;
            pixels[index] = (uint8_t)(color >> 8);
            pixels[index + 1] = (uint8_t)color;
        }
    }
    ILI9341_DrawImageRGB565(x, y, 16, 16, pixels, sizeof(pixels));
}

